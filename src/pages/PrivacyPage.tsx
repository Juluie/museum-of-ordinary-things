import { useApp } from '../lib/app-context.ts'
import { useDocumentTitle } from '../lib/use-document-title.ts'

/** Значения, которые владелец проекта должен заполнить сам. Не выдумываем их. */
function Fill({ children }: { children: string }) {
  return <mark className="placeholder">[заполнить: {children}]</mark>
}

export function PrivacyPage() {
  const { config } = useApp()
  useDocumentTitle('Приватность')
  return (
    <article className="prose">
      <h1>Как музей обращается с данными</h1>
      <p className="notice notice-info">
        Это фактическое описание того, как устроен сайт. Это не юридический документ и не заявление о соответствии
        какому-либо закону.
      </p>
      {config.mode === 'demo' && (
        <p className="notice notice-demo">
          Сейчас открыта демо-версия: форма ничего не отправляет и не сохраняет.
        </p>
      )}

      <h2>Кто отвечает за проект</h2>
      <p>
        Оператор проекта: <Fill>имя или название</Fill>. Связаться: <Fill>email для обращений</Fill>.
      </p>

      <h2>Что мы получаем, когда ты добавляешь вещь</h2>
      <ul>
        <li>Фотографию предмета. На сервере она уменьшается и пересохраняется без метаданных: EXIF, геолокация и данные камеры удаляются. Исходный файл не хранится.</li>
        <li>Название, историю, описание фотографии, а также подпись и «как давно хранится», если ты их заполнишь.</li>
        <li>Время отправки и версию текста согласия.</li>
      </ul>

      <h2>Что мы не храним</h2>
      <ul>
        <li>Аккаунтов посетителей нет, регистрация не нужна.</li>
        <li>Сырой IP-адрес в базе музея не хранится. Для ограничения частоты отправки используется хеш адреса с секретным ключом (HMAC); такие записи удаляются примерно через двое суток. Это не полная анонимизация.</li>
        <li>Аналитики и рекламных трекеров на сайте нет. Шрифты загружаются с этого же сайта.</li>
        <li>Текст формы не сохраняется в браузере между визитами.</li>
      </ul>

      <h2>Кто видит отправленное</h2>
      <p>
        До проверки фото и история видны только хранителю музея. После одобрения — всем посетителям сайта. Фотографии
        хранятся в закрытом хранилище, посетители получают временные ссылки только на опубликованные экспонаты.
      </p>

      <h2>Сервисы, через которые работает сайт</h2>
      <ul>
        <li>Supabase — база данных, хранилище фото, вход хранителя. Регион: <Fill>регион проекта Supabase</Fill>.</li>
        <li>Cloudflare Pages — размещение сайта.</li>
        <li>Cloudflare Turnstile — проверка «я не робот» в форме отправки.</li>
      </ul>

      <h2>Сколько хранится</h2>
      <p>
        Опубликованные экспонаты — пока существует музей или до просьбы удалить. Отклонённые записи —{' '}
        <Fill>реальный срок хранения отклонённых записей</Fill>; фото отклонённых вещей удаляется сразу. Резервные копии
        — <Fill>срок хранения резервных копий</Fill>.
      </p>

      <h2>Как удалить свою вещь</h2>
      <p>
        Напиши на <Fill>email для обращений</Fill> и укажи ссылку на экспонат или его номер. После удаления музей
        перестаёт показывать вещь и удаляет фото из хранилища. Копии, которые кто-то уже скачал, мы удалить не можем.
      </p>
    </article>
  )
}
